/** Returns an <svg class="icon"> element. Unknown names render an empty icon (and warn in dev). */
export function icon(name, { size, className = '', title } = {}) {
  const el = s('svg', {
    class: `icon ${className}`.trim(),
    viewBox: '0 0 24 24',
    'aria-hidden': title ? undefined : 'true',
    role: title ? 'img' : undefined,
    width: size || undefined,
    height: size || undefined,
    style: size ? `width:${size}px;height:${size}px` : undefined,
  });
  const body = P[name];
  if (!body && typeof console !== 'undefined') console.warn('[icon] unknown icon:', name);
  el.innerHTML = (title ? `<title>${title}</title>` : '') + (body || '');
  return el;
}

/** Same icon as an HTML string (for markup built with template strings). */
export function iconHTML(name, size) {
  const st = size ? ` style="width:${size}px;height:${size}px"` : '';
  return `<svg class="icon" viewBox="0 0 24 24" aria-hidden="true"${st}>${P[name] || ''}</svg>`;
}
